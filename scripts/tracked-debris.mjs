/**
 * @file Nothing a tool left behind is tracked.
 *
 * A coverage report, a `cwd.txt` a session wrote where it stood, a
 * `.backup` of a manifest and a lockfile below the root (the workspace has
 * one, at the root) are things tools make. Tracked, they go stale and are
 * read as if they meant something: a nested lockfile was audited in CI
 * long after it stopped describing what is installed. This reads the list
 * of tracked files and fails on any of them. One kind of file is excused
 * by name: the lockfiles of the audit coverage check's fixture
 * repositories, which are a test's input and are lockfiles on purpose.
 *
 * Run via `npm run lint:debris`, in the repository whose tracked files are
 * meant (it asks git in the folder it is run from). The list may be given
 * on standard input instead, each path ended by a NUL as `git ls-files -z`
 * writes them, when the first argument is `--stdin`.
 *
 * @module
 */

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

/** What is debris, and why: a test of the path, and the words for it. */
const KINDS = [
  { test: (path) => path.split('/').includes('coverage'), why: 'a coverage report (generated by the tests)' },
  { test: (path) => path.split('/').pop() === 'cwd.txt', why: 'a session\'s working-folder note' },
  { test: (path) => path.endsWith('.backup'), why: 'a backup copy of a file' },
  { test: (path) => path.includes('/') && path.split('/').pop() === 'package-lock.json', why: 'a lockfile below the root (the workspace has one, at the root)' },
];

// Asked for with `-z`: paths as they are, each ended by a NUL. Without it git prints for people, and
// quotes and escapes any path with a byte outside ASCII, which would then match nothing here.
const listing = process.argv[2] === '--stdin'
  ? readFileSync(0, 'utf8')
  : execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const tracked = listing.split('\0').filter((path) => path !== '');
if (tracked.length === 0) {
  console.error('tracked-debris: no tracked files were listed: nothing was checked');
  process.exit(1);
}

/** The audit coverage check's fixture lockfiles: `scripts/fixtures/audit-coverage/<case>/package-lock.json`. */
const FIXTURE_LOCKFILE = /^scripts\/fixtures\/audit-coverage\/[^/]+\/package-lock\.json$/;

const found = [];
for (const path of tracked) {
  // The one exception, by name: the lockfiles of the small repositories the audit coverage check is tested
  // on. They are a test's input, made to be lockfiles below the root; nothing else under them is excused.
  if (FIXTURE_LOCKFILE.test(path)) continue;
  const kind = KINDS.find((one) => one.test(path));
  if (kind !== undefined) found.push(`  ${path}: ${kind.why}`);
}
if (found.length > 0) {
  console.error(`tracked-debris: ${found.length} tracked file(s) that a tool left behind:`);
  for (const line of found.slice(0, 40)) console.error(line);
  if (found.length > 40) console.error(`  … and ${found.length - 40} more`);
  console.error('Remove them from the tree (git rm) and leave them to .gitignore.');
  process.exit(1);
}
console.log(`tracked-debris: none among ${tracked.length} tracked files.`);
